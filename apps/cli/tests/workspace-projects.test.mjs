      "const localCollision = createWorkspaceProject({ userId: owner, appId: 'workspace', nodeId: null, path: join(root, 'local-collision'), platform: 'win32' });",
      "assert.throws(() => updateDefaultWorkspaceProjectPath(owner, first.id, migratedPath, localCollision.path, 'win32'), /另一个项目/u);",
      "assert.equal(removeWorkspaceProject(owner, localCollision.id, 'workspace'), true);",
      "const migratedPathV3 = join(root, 'Documents', 'LFAA', 'default-workspace-v3');",
      "assert.equal(updateDefaultWorkspaceProjectPath(owner, first.id, migratedPath, migratedPathV3, 'win32').path, migratedPathV3, '本机项目路径更新按 NULL 节点执行');",
      "const gitSource = createWorkspaceProject({ userId: owner, appId: 'workspace', nodeId: nodeA, path: join(root, 'GitSource'), platform: 'linux' });",
      "const managedTree = createWorkspaceGitWorktree({ userId: owner, appId: 'workspace', sourceProjectId: gitSource.id, nodeId: nodeA, path: join(root, 'managed-tree'), worktreeRoot: join(root, 'managed-tree'), worktreeId: randomUUID(), projectRelativePath: '', branch: 'codex/workspace-owner', baseCommit: 'a'.repeat(40), sourceHead: 'b'.repeat(40), platform: 'linux' });",
