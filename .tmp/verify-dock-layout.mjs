import { existsSync } from "node:fs";
import { chromium } from "playwright-core";
const candidates = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Google/Chrome/Application/chrome.exe"];
const executablePath = candidates.find((p) => existsSync(p));
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text().slice(0, 200)); });
await page.goto("http://127.0.0.1:5173/", { waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(1500);
await page.evaluate(() => { localStorage.setItem("lfaa:terminal-placement", "bottom"); localStorage.removeItem("lfaa:bottom-panel-height"); });
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(3000);
const box = await page.evaluate(() => {
  const dock = document.querySelector("[data-bottom-dock]")?.getBoundingClientRect();
  const rail = document.querySelector("[data-region='primary-navigation']")?.getBoundingClientRect();
  return { dock: dock ? {x: Math.round(dock.x), y: Math.round(dock.y), w: Math.round(dock.width), h: Math.round(dock.height)} : null, rail: rail ? {x: Math.round(rail.x), w: Math.round(rail.width), h: Math.round(rail.height)} : null, viewport: window.innerWidth };
});
await page.screenshot({ path: "E:/lfaa/.tmp/shots/dock-layout-fixed.png" });
console.log(JSON.stringify({ ...box, errors: errors.slice(0, 4) }, null, 1));
await browser.close();
