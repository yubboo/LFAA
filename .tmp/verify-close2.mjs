import { existsSync } from "node:fs";
import { chromium } from "playwright-core";
const candidates = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Google/Chrome/Application/chrome.exe"];
const executablePath = candidates.find((p) => existsSync(p));
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text().slice(0, 160)); });
page.on("pageerror", (e) => errors.push(`PAGEERROR ${e.message.slice(0, 160)}`));
await page.goto("http://127.0.0.1:5173/", { waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(1500);
const run = async (placement) => {
  await page.evaluate((p) => localStorage.setItem("lfaa:terminal-placement", p), placement);
  await page.reload({ waitUntil: "domcontentloaded" });
  await page.waitForSelector("[data-columns]", { timeout: 60000 });
  await page.waitForTimeout(2200);
  const rail = page.locator('[data-region="context-panel"] button[aria-label="终端"]').first();
  if (await rail.count()) await rail.click();
  await page.waitForTimeout(1500);
  const tabs = () => page.evaluate(() => [...document.querySelectorAll('[role="tablist"] [role="tab"]')].map((t) => t.textContent?.trim()));
  const opened = await tabs();
  const closeBtns = page.locator('[role="tablist"] button[aria-label*="关闭"]');
  const n = await closeBtns.count();
  if (n) await closeBtns.first().click();
  await page.waitForTimeout(1200);
  const after1 = await tabs();
  const n2 = await page.locator('[role="tablist"] button[aria-label*="关闭"]').count();
  if (n2) await page.locator('[role="tablist"] button[aria-label*="关闭"]').first().click();
  await page.waitForTimeout(1000);
  const after2 = await tabs();
  return { placement, opened, closeBtns: n, after1, after2, errors: errors.slice(0, 3) };
};
const right = await run("right");
const bottom = await run("bottom");
console.log(JSON.stringify({ right, bottom }, null, 1));
await browser.close();
