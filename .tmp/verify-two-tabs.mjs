import { existsSync } from "node:fs";
import { chromium } from "playwright-core";
const candidates = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Google/Chrome/Application/chrome.exe"];
const executablePath = candidates.find((p) => existsSync(p));
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text().slice(0, 140)); });
page.on("pageerror", (e) => errors.push(`PAGEERROR ${e.message.slice(0, 140)}`));
await page.goto("http://127.0.0.1:5173/", { waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(1500);
await page.evaluate(() => localStorage.setItem("lfaa:terminal-placement", "right"));
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(2200);
const tabs = () => page.evaluate(() => [...document.querySelectorAll('[role="tablist"] [role="tab"]')].map((t) => t.textContent?.trim()));
// 打开终端与后台任务两个标签
const railTerminal = page.locator('[data-region="context-panel"] button[aria-label="终端"]').first();
if (await railTerminal.count()) await railTerminal.click();
await page.waitForTimeout(1000);
const railJobs = page.locator('[data-region="context-panel"] button[aria-label="后台任务"]').first();
if (await railJobs.count()) await railJobs.click();
await page.waitForTimeout(1000);
const two = await tabs();
// 关闭终端标签
const closeTerminal = page.locator('[role="tablist"] [role="tab"] >> text=终端').first();
const closeBtn = page.locator('[role="tablist"] button[aria-label*="关闭"]');
if (await closeBtn.count()) await closeBtn.first().click();
await page.waitForTimeout(1500);
const afterClose = await tabs();
await page.waitForTimeout(2500);
const afterWait = await tabs();
console.log(JSON.stringify({ two, afterClose, afterWait, errors: errors.slice(0, 3) }, null, 1));
await browser.close();
