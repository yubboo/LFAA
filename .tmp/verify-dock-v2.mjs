import { existsSync } from "node:fs";
import { chromium } from "playwright-core";
const candidates = ["C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Microsoft/Edge/Application/msedge.exe","C:/Program Files/Google/Chrome/Application/chrome.exe"];
const executablePath = candidates.find((p) => existsSync(p));
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text().slice(0, 160)); });
page.on("pageerror", (e) => errors.push(`PAGEERROR ${e.message.slice(0, 160)}`));
await page.goto("http://127.0.0.1:5173/", { waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(1500);
await page.evaluate(() => { localStorage.setItem("lfaa:terminal-placement", "bottom"); localStorage.removeItem("lfaa:bottom-panel-height"); });
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-columns]", { timeout: 60000 });
await page.waitForTimeout(3000);
const info = await page.evaluate(() => {
  const dock = document.querySelector('section[aria-label="底部终端"]')?.getBoundingClientRect();
  const workbench = document.querySelector(".workbench")?.getBoundingClientRect() ?? null;
  const rows = document.querySelector(".xterm-rows");
  return { dock: dock ? { x: Math.round(dock.x), w: Math.round(dock.width), y: Math.round(dock.y), h: Math.round(dock.height) } : null, wb: workbench ? { x: Math.round(workbench.x), w: Math.round(workbench.width) } : null, xterm: Boolean(rows), screen: rows?.textContent?.slice(0, 40) ?? "" };
});
await page.screenshot({ path: "E:/lfaa/.tmp/shots/dock-v2.png" });
console.log(JSON.stringify({ ...info, errors: errors.slice(0, 4) }, null, 1));
await browser.close();
